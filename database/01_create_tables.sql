CREATE TABLE USERS (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name VARCHAR2(100),
    email VARCHAR2(100),
    password_hash VARCHAR2(255),
    points NUMBER DEFAULT 0,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE CATEGORIES (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    category_name VARCHAR2(100)
);

CREATE TABLE PLACES (
    place_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    category_id NUMBER,
    place_name VARCHAR2(150),
    address VARCHAR2(255),
    description VARCHAR2(500),
    latitude NUMBER(10,7),
    longitude NUMBER(10,7),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE CHECKINS (
    checkin_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id NUMBER,
    place_id NUMBER,
    checked_in_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    checked_out_at TIMESTAMP
);

CREATE TABLE CONDITION_REPORTS (
    report_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    checkin_id NUMBER,
    user_id NUMBER,
    place_id NUMBER,
    crowd_level VARCHAR2(10),
    socket_available CHAR(1),
    wifi_speed VARCHAR2(10),
    wifi_mbps NUMBER(8,2),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE POINT_LOG (
    point_log_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id NUMBER,
    points_change NUMBER,
    description VARCHAR2(255),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE SETTINGS (
    setting_key VARCHAR2(50),
    setting_value VARCHAR2(100),
    description VARCHAR2(255)
);

CREATE TABLE AUDIT_LOG (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id NUMBER,
    action_type VARCHAR2(50),
    table_name VARCHAR2(100),
    record_id NUMBER,
    details VARCHAR2(500),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

SELECT TABLE_NAME
FROM USER_TABLES
ORDER BY TABLE_NAME;
